# The placeholders are replaced with json.dumps()'d values, so any path or
# parameter value is safely embedded as a JS string literal.

_JS_PAGINATED = """
async () => {
  const path = __PATH__;
  const perPage = __PER_PAGE__;
  const maxPages = __MAX_PAGES__;
  const startPage = __START_PAGE__;
  const startCursor = __START_CURSOR__;
  const slim = (item) => {
    if (!item || typeof item !== "object") { return item; }
    const copy = { ...item };
    delete copy.metadata;
    delete copy.conns_active_at;
    delete copy.conns_inactive_at;
    delete copy.config_src;
    if (Array.isArray(copy.connections)) {
      copy.connections = copy.connections.slice(0, 8).map((c) => ({
        id: c.id || c.uuid || "",
        colo_name: c.colo_name || "",
        is_pending_reconnect: Boolean(c.is_pending_reconnect),
        origin_ip: c.origin_ip || null,
      }));
    }
    return copy;
  };
  const out = [];
  let page = startPage;
  let cursor = startCursor;
  let previousCursor = null;
  while (page <= maxPages) {
    const query = { per_page: perPage, page };
    if (cursor) { query.cursor = cursor; }
    let qs = "per_page=" + perPage + "&page=" + page;
    if (cursor) { qs += "&cursor=" + encodeURIComponent(cursor); }
    const response = await (typeof cloudflare !== "undefined"
      ? cloudflare.request({ method: "GET", path, query })
      : codemode.request({ method: "GET", path: path + "?" + qs }));
    const rawItems = (response && response.result) || [];
    const items = Array.isArray(rawItems) ? rawItems.map(slim) : [];
    if (out.length > 0 && JSON.stringify(out).length + JSON.stringify(items).length > 16000) {
      return { result: out, next_page: page, next_cursor: cursor };
    }
    out.push(...items);
    const info = (response && response.result_info) || {};
    const totalPages = info.total_pages || (
      info.total_count && info.per_page ? Math.ceil(info.total_count / info.per_page) : 1
    );
    cursor = (info.cursors && info.cursors.after) || info.cursor || null;
    if (items.length === 0) { break; }
    if (cursor && cursor === previousCursor) { break; }
    previousCursor = cursor;
    if (!cursor && page >= totalPages) { break; }
    page += 1;
    if (JSON.stringify(out).length > 16000) {
      return { result: out, next_page: page, next_cursor: cursor };
    }
  }
  return out;
}
"""

