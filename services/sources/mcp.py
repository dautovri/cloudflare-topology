    def _discover_account_id(self) -> str:
        """Auto-discover the account ID for the token from /accounts."""
        logger.info("No account ID provided, discovering from token via MCP...")
        code = _render(_JS_PAGINATED, path="/accounts", per_page=2, max_pages=1)
        accounts = _unwrap_items(self._call_execute(code))
        if not accounts:
            raise CloudflareAPIError("No accounts found for this API token (via MCP)")
        first = accounts[0]
        account_id = str(first.get("id", ""))
        total = len(accounts)
        if total == 1:
            logger.info("Discovered account: %s (%s)", first.get("name", account_id), account_id)
        else:
            logger.warning(
                "Token has access to %d+ accounts, using first: %s (%s). "
                "Set CLOUDFLARE_ACCOUNT_ID to override.",
                total, first.get("name", account_id), account_id,
            )
        return account_id

    def _try_fetch(self, name: str, fetcher):
        """Call fetcher and return its result, returning [] on 403 permission errors."""
        return shared.try_fetch(name, fetcher)

    def fetch_topology(
        self,
        include_tunnel_configs: bool = True,
        include_app_policies: bool = True,
        include_devices: bool = True,
        include_gateway_rules: bool = False,
    ) -> CloudflareTopology:
        """Fetch the complete Zero Trust topology through the MCP server.

        Same signature and semantics as
        :meth:`services.cloudflare_api.CloudflareAPIClient.fetch_topology`;
        the resource families are fetched as individual execute calls and
        parsed with the shared parsers.

        Args:
            include_tunnel_configs: Fetch detailed tunnel configurations
            include_app_policies: Fetch policies for each application
            include_devices: Fetch WARP devices
            include_gateway_rules: Fetch Gateway firewall rules

        Returns:
            CloudflareTopology with all fetched data
        """
        logger.info("Starting topology fetch via MCP server %s ...", self.url)

        # tunnels
        tunnel_items = self._try_fetch("tunnels", self.list_tunnels)
        tunnels = [shared.parse_tunnel(item) for item in tunnel_items]

        # tunnel configs (batched inside the sandbox when multiple tunnels exist)
        if include_tunnel_configs and tunnels:
            remote = [t for t, item in zip(tunnels, tunnel_items) if item.get("remote_config")]
            if len(remote) == 1:
                cfg = self.get_tunnel_config(remote[0].id)
                if cfg:
                    remote[0].config = cfg
            elif len(remote) > 1:
                self._attach_tunnel_configs_batched(remote)

        # applications
        app_items = self._try_fetch("applications", self.list_applications)
        applications = [shared.parse_application(item) for item in app_items]

        # application policies (attached to their applications)
        if include_app_policies and applications:
            def _attach_policies(app: Any) -> Any:
                policy_items = self.get_application_policies(app.id)
                app.policies = [shared.parse_policy(p) for p in policy_items]
                return app.policies
            shared.run_parallel(_attach_policies, applications, max_workers=4)

        # reusable policies, groups, identity providers
        policy_items = self._try_fetch("policies", self.list_policies)
        policies = [shared.parse_policy(item) for item in policy_items]

        group_items = self._try_fetch("groups", self.list_groups)
        groups = [shared.parse_group(item) for item in group_items]

        idp_items = self._try_fetch("identity_providers", self.list_identity_providers)
        identity_providers = [shared.parse_identity_provider(item) for item in idp_items]

        # networks
        vnet_items = self._try_fetch("virtual_networks", self.list_virtual_networks)
        virtual_networks = [shared.parse_virtual_network(item) for item in vnet_items]

        route_items = self._try_fetch("routes", self.list_routes)
        routes = [shared.parse_route(item) for item in route_items]

        # devices
        devices = []
        if include_devices:
            device_items = self._try_fetch("devices", self.list_devices)
            devices = [shared.parse_device(item) for item in device_items]

        # gateway rules
        gateway_rules = []
        if include_gateway_rules:
            rule_items = self._try_fetch("gateway_rules", self.list_gateway_rules)
            gateway_rules = [shared.parse_gateway_rule(item) for item in rule_items]

        topology = shared.build_topology(
            self.config.account_id,
            datetime.now(timezone.utc).isoformat(),
            tunnels=tunnels,
            applications=applications,
            policies=policies,
            groups=groups,
            devices=devices,
            virtual_networks=virtual_networks,
            routes=routes,
            identity_providers=identity_providers,
            gateway_rules=gateway_rules,
        )

        logger.info("Topology fetch complete via MCP. Total resources: %d", topology.total_resources)
        return topology


