def _render(template: str, **params: Any) -> str:
    """Substitute __NAME__ placeholders with JSON-encoded values (safe quoting)."""
    params.setdefault("start_page", 1)
    params.setdefault("start_cursor", None)
    code = template
    for name, value in params.items():
        code = code.replace(f"__{name.upper()}__", json.dumps(value))
    return code


def _unwrap_items(payload: Any, _depth: int = 0) -> List[Dict[str, Any]]:
    """Extract the item list from a tools/call result or API envelope.

    Peels up to three nested ``result`` members (JSON-RPC result -> envelope
    -> body) before giving up and returning an empty list.
    """
    if payload is None or _depth > 3:
        return []
    if isinstance(payload, list):
        return [item for item in payload if isinstance(item, dict)]
    if isinstance(payload, dict):
        if "result" in payload:
            return _unwrap_items(payload["result"], _depth + 1)
        for key in ("items", "data", "value", "records"):
            if key in payload:
                return _unwrap_items(payload[key], _depth + 1)
        return [payload]
    return []


def _unwrap_single(payload: Any, _depth: int = 0) -> Optional[Dict[str, Any]]:
    """Extract a single object from a tools/call result or API envelope.

    Mirrors :func:`_unwrap_items` for endpoints whose result is one object
    (e.g. a tunnel configuration). Peels up to three nested ``result``
    members; returns None for empty/absent payloads.
    """
    if payload is None or _depth > 3:
        return None
    if isinstance(payload, dict):
        if "result" in payload:
            return _unwrap_single(payload["result"], _depth + 1)
        return payload
    return None


def _parse_stream(body: str, request_id: Any) -> Optional[Dict[str, Any]]:
    """Parse an MCP response body: either a JSON document or SSE frames.

    Returns the JSON-RPC message whose ``id`` matches ``request_id``, or the
    sole message when it carries no ``id`` (notification echo). Returns None
    when no matching message is found.
    """
    content = body or ""
    candidates = [content]
    # SSE framing: collect `data:` field values from each `event: message` block.
    if "data:" in content:
        for frame in re.split(r"\n\n+", content.strip()):
            for line in frame.splitlines():
                if line.startswith("data:"):
                    candidates.append(line[5:].lstrip())

    for candidate in candidates:
        candidate = candidate.strip()
        if not candidate:
            continue
        try:
            message = json.loads(candidate)
        except ValueError:
            continue
        if isinstance(message, dict):
            if "id" not in message or message["id"] == request_id:
                return message
    return None


class ZeroTrustMCPSource:
    """Topology source that calls the Cloudflare API via the remote MCP server.

    Constructor arguments:
        config: Application configuration; ``api_token`` is used as the Bearer
            token, ``account_id`` is auto-discovered when empty (same as the
            REST client), ``mcp_url`` selects the server endpoint.
        url: Explicit Streamable HTTP endpoint (overrides ``config.mcp_url``).
        timeout: Per-request timeout in seconds (default MCP_REQUEST_TIMEOUT).

    The initialize handshake is performed lazily on the first request and
    retried up to MCP_MAX_ATTEMPTS times with an exponential backoff
    (base MCP_BACKOFF_FACTOR).
    """

    def __init__(
        self,
        config: Config,
        url: Optional[str] = None,
        timeout: Optional[int] = None,
        max_attempts: int = MCP_MAX_ATTEMPTS,
        backoff_factor: float = MCP_BACKOFF_FACTOR,
    ):
        self.config = config
        self.url = (url or getattr(config, "mcp_url", "") or MCP_URL).rstrip("/")
        self.timeout = timeout or MCP_REQUEST_TIMEOUT
        self.max_attempts = max(1, max_attempts)
        self.backoff_factor = backoff_factor

        self.session = requests.Session()
        self.session.headers.update({
            "Authorization": f"Bearer {config.api_token}",
            "Content-Type": "application/json",
            # Accept both JSON and Server-Sent Events per the MCP transport spec.
            "Accept": "application/json, text/event-stream",
            "User-Agent": f"{MCP_CLIENT_NAME}/{MCP_CLIENT_VERSION} (mcp-client; python-requests)",
        })

        self._request_ids = itertools.count(1)
        self._session_id: Optional[str] = None
        self._initialized = False
        self._initialize_lock = threading.Lock()

        self._last_request_time = 0.0
        self._rate_limit_lock = threading.Lock()

        # Account discovery is deferred: it needs the live server, so it runs
        # lazily on first use (same net result as the REST client, which also
        # only hits /accounts once, but without blocking construction).
        self._account_checked = bool(self.config.account_id)

    # -----------------------------------------------------------------------
    # Transport plumbing
    # -----------------------------------------------------------------------

    def _ensure_account_id(self) -> str:
        """Ensure config.account_id is populated, discovering it once if needed."""
        if not self._account_checked:
            self._account_checked = True
            if not self.config.account_id:
                self.config.account_id = self._discover_account_id()
        return self.config.account_id

    def _rate_limit(self) -> None:
        """Apply rate limiting between requests (thread-safe, token gap)."""
        min_interval = 1.0 / MAX_REQUESTS_PER_SECOND
        with self._rate_limit_lock:
            elapsed = time.time() - self._last_request_time
            if elapsed < min_interval:
                time.sleep(min_interval - elapsed)
            self._last_request_time = time.time()

    def _headers(self) -> Dict[str, str]:
        """Assemble the headers for one JSON-RPC exchange."""
        headers = {MCP_PROTOCOL_HEADER: MCP_PROTOCOL_VERSION}
        if self._session_id:
            headers[MCP_SESSION_HEADER] = self._session_id
        return headers

    def _rpc(self, method: str, params: Dict[str, Any], expect_response: bool = True) -> Dict[str, Any]:
        """Send a single JSON-RPC message and return the decoded response message.

        Raises CloudflareAPIError on transport failure (after the final retry),
        on a JSON-RPC error object, or when the response message does not match
        the request id.
        """
        request_id = next(self._request_ids)
        payload: Dict[str, Any] = {"jsonrpc": "2.0", "method": method}
        if expect_response:
            payload["id"] = request_id
        if params:
            payload["params"] = params

        last_error: Optional[CloudflareAPIError] = None
        for attempt in itertools.count(1):
            if attempt > self.max_attempts:
                break
            try:
                self._rate_limit()
                response = self.session.post(
                    self.url,
                    json=payload,
                    headers=self._headers(),
                    timeout=self.timeout,
                )
            except requests.exceptions.Timeout:
                last_error = CloudflareAPIError(
                    f"MCP request timeout for {method} at {self.url}"
                )
            except requests.exceptions.RequestException as exc:
                last_error = CloudflareAPIError(f"MCP request failed: {exc}")
            else:
                if response.status_code in MCP_RETRY_STATUSES:
                    last_error = CloudflareAPIError(
                        f"MCP server returned HTTP {response.status_code}: "
                        f"{response.text[:200]}",
                        status_code=response.status_code,
                    )
                elif response.status_code >= 400:
                    # Non-retryable (e.g. 401 Unauthorized, 403 Forbidden).
                    raise CloudflareAPIError(
                        f"MCP server returned HTTP {response.status_code}: "
                        f"{response.text[:200]}",
                        status_code=response.status_code,
                    )
                else:
                    session_id = response.headers.get(MCP_SESSION_HEADER)
                    if session_id:
                        self._session_id = session_id
                    if not expect_response:
                        return {}
                    message = _parse_stream(response.text, request_id)
                    if message is None:
                        raise CloudflareAPIError(
                            f"No matching JSON-RPC response for {method} "
                            f"(id={request_id}): {response.text[:200]}",
                            status_code=response.status_code,
                        )
                    if "error" in message:
                        error = message["error"] or {}
                        raise CloudflareAPIError(
                            f"JSON-RPC error for {method}: "
                            f"[{error.get('code', '?')}] {error.get('message', 'unknown')}",
                        )
                    result = message.get("result", {})
                    return result if isinstance(result, dict) else {"value": result}

            # Transient failure: back off and retry the initial sequence.
            if attempt < self.max_attempts:
                delay = self.backoff_factor * (2 ** (attempt - 1))
                logger.warning(
                    "MCP %s failed (attempt %d/%d): %s -- retrying in %.1fs",
                    method, attempt, self.max_attempts, last_error, delay,
                )
                time.sleep(delay)

        assert last_error is not None
        raise last_error

    def _ensure_initialized(self) -> None:
        """Perform the MCP initialize handshake once (thread-safe)."""
        if self._initialized:
            return
        with self._initialize_lock:
            if self._initialized:
                return
            result = self._rpc("initialize", {
                "protocolVersion": MCP_PROTOCOL_VERSION,
                "clientInfo": {
                    "name": MCP_CLIENT_NAME,
                    "title": "Cloudflare Topology Mapper",
                    "version": MCP_CLIENT_VERSION,
                },
                "capabilities": {},
            })
            negotiated = result.get("protocolVersion") if isinstance(result, dict) else None
            if negotiated and negotiated != MCP_PROTOCOL_VERSION:
                logger.debug("MCP server negotiated protocolVersion %s", negotiated)
            server_info = (result or {}).get("serverInfo") or {}
            logger.info(
                "Connected to MCP server %s (version %s)",
                self.url, server_info.get("version", "unknown"),
            )
            # notifications/initialized -- a notification, no response expected.
            self._rpc("notifications/initialized", {}, expect_response=False)
            self._initialized = True

    # -----------------------------------------------------------------------
    # Tool access
    # -----------------------------------------------------------------------

    def list_tools(self) -> List[Dict[str, Any]]:
        """Return the tools offered by the server (diagnostics / discover)."""
        self._ensure_initialized()
        result = self._rpc("tools/list", {})
        tools = result.get("tools") if isinstance(result, dict) else None
        return tools if isinstance(tools, list) else []

    def search_endpoints(self, pattern: str) -> Any:
        """Ask the server's ``search`` tool which API operations match a pattern.

        Diagnostic helper for debugging which endpoints the sandbox can reach
        (e.g. ``source.search_endpoints("/cfd_tunnel")``). Returns the decoded
        value the search program produced.
        """
        code = (
            "async () => {\n"
            "  const doc = typeof spec !== 'undefined' ? spec : await codemode.spec();\n"
            "  return Object.entries(doc.paths)\n"
            f"    .filter(([path]) => path.includes({json.dumps(pattern)}))\n"
            "    .map(([path, operations]) => ({ path, methods: Object.keys(operations) }));\n"
            "}"
        )
        return self._call_tool(MCP_SEARCH_TOOL, code)

    def _call_execute(self, code: str) -> Any:
        """Call the sandbox tool ``execute`` with the given JavaScript program.

        Returns the value the sandboxed program returned, or None.
        """
        extra = {"account_id": self.config.account_id} if self.config.account_id else None
        return self._call_tool(MCP_EXECUTE_TOOL, code, extra_args=extra)

    def _call_tool(
        self,
        tool_name: str,
        code: str,
        extra_args: Optional[Dict[str, Any]] = None,
    ) -> Any:
        """Invoke a Code-Mode tool and decode the value its program returned."""
        self._ensure_initialized()
        logger.debug("MCP %s program:\n%s", tool_name, code.strip())
        arguments: Dict[str, Any] = {"code": code}
        if extra_args:
            arguments.update(extra_args)
        result = self._rpc("tools/call", {
            "name": tool_name,
            "arguments": arguments,
        })
        if not isinstance(result, dict):
            raise CloudflareAPIError(f"Unexpected {tool_name} result: {result!r}")
        if result.get(_RESULT_IS_ERROR, False):
            text = _tool_text(result)
            status = _status_from_text(text)
            raise CloudflareAPIError(
                f"{tool_name} failed: {text or 'unknown error'}",
                status_code=status,
            )
        if "structuredContent" in result:
            return result["structuredContent"]
        text = _tool_text(result)
        if text is None:
            return None
        try:
            return json.loads(text)
        except ValueError:
            raise CloudflareAPIError(
                f"{tool_name} returned non-JSON text: {text[:200]}"
            )

    # -----------------------------------------------------------------------
    # Requests (generated sandbox programs)
    # -----------------------------------------------------------------------

    def _get_endpoint(self, template: str, **kwargs: Any) -> str:
        """Format an endpoint template with parameters (same as the REST client)."""
        account_id = self._ensure_account_id()
        return shared.format_endpoint(account_id, template, **kwargs)

    def _fetch_paginated(self, endpoint: str, per_page: int = 25, max_pages: int = 50) -> List[Dict[str, Any]]:
        """Run the pagination loop inside the sandbox; return all items.

        Both the classic ``page``/``per_page``/``total_pages`` pagination and
        the cursor-based ``result_info.cursors.after`` scheme are handled by
        the same generated program. If a large account exceeds the MCP server's
        per-call output cap (~24 KB), the sandbox yields a chunk with
        ``next_page``/``next_cursor`` and this method fetches the next chunk.
        """
        all_items: List[Dict[str, Any]] = []
        start_page = 1
        start_cursor: Optional[str] = None
        while start_page <= max_pages:
            code = _render(
                _JS_PAGINATED,
                path=endpoint,
                per_page=per_page,
                max_pages=max_pages,
                start_page=start_page,
                start_cursor=start_cursor,
            )
            payload = self._call_execute(code)
            all_items.extend(_unwrap_items(payload))
            if isinstance(payload, dict) and (payload.get("next_page") or payload.get("next_cursor")):
                next_page = int(payload.get("next_page") or (start_page + 1))
                next_cursor = payload.get("next_cursor")
                if next_page <= start_page and next_cursor == start_cursor:
                    break
                start_page = next_page
                start_cursor = next_cursor
            else:
                break
        return all_items

    def _fetch_list(self, endpoint: str) -> List[Dict[str, Any]]:
        """Fetch an endpoint whose ``result`` member is a list or an object."""
        code = _render(_JS_LIST, path=endpoint)
        return _unwrap_items(self._call_execute(code))

    # -----------------------------------------------------------------------
    # Resource access -- one method per resource family (models mirror the
    # REST client's API so both sources stay drop-in compatible)
    # -----------------------------------------------------------------------

    def list_tunnels(self) -> List[Dict[str, Any]]:
        """Fetch all Cloudflare Tunnels."""
        endpoint = self._get_endpoint(APIEndpoints.LIST_TUNNELS)
        items = self._fetch_paginated(endpoint)
        logger.info("Fetched %d tunnels (MCP)", len(items))
        return items

    def get_tunnel_config(self, tunnel_id: str) -> Optional[TunnelConfig]:
        """Fetch a tunnel's configuration; returns None when unavailable."""
        try:
            endpoint = self._get_endpoint(APIEndpoints.GET_TUNNEL_CONFIG, tunnel_id=tunnel_id)
            code = _render(_JS_CONFIG, path=endpoint)
            return shared.parse_tunnel_config(_unwrap_single(self._call_execute(code)))
        except CloudflareAPIError as exc:
            logger.warning("Could not fetch config for tunnel %s via MCP: %s", tunnel_id, exc)
            return None

    def _attach_tunnel_configs_batched(self, tunnels: List[Tunnel], batch_size: int = 25) -> None:
        """Fetch tunnel configurations in sandbox batches using Promise.all."""
        account_id = self._ensure_account_id()
        by_id = {t.id: t for t in tunnels}
        ids = list(by_id.keys())
        for idx in range(0, len(ids), batch_size):
            chunk = ids[idx:idx + batch_size]
            code = _render(_JS_BATCH_CONFIGS, account_id=account_id, tunnel_ids=chunk)
            try:
                raw = _unwrap_single(self._call_execute(code)) or {}
            except CloudflareAPIError as exc:
                logger.warning("Could not fetch tunnel config batch via MCP: %s", exc)
                continue
            for tun_id, cfg_dict in raw.items():
                if tun_id in by_id and isinstance(cfg_dict, dict):
                    by_id[tun_id].config = shared.parse_tunnel_config(cfg_dict)

