def _tool_text(result: Dict[str, Any]) -> Optional[str]:
    """Concatenate the text content blocks of a tools/call result."""
    blocks = result.get("content")
    if not isinstance(blocks, list):
        return None
    parts = [block.get("text", "") for block in blocks
             if isinstance(block, dict) and block.get("type") == "text"]
    if not parts:
        return None
    return "\n".join(part for part in parts if part)


def _status_from_text(text: Optional[str]) -> Optional[int]:
    """Best-effort extraction of an HTTP status code from an error text."""
    if not text:
        return None
    lowered = text.lower()
    if (
        "10000: authentication error" in lowered
        or "not authorized" in lowered
        or "forbidden" in lowered
        or "insufficient_scope" in lowered
    ):
        return 403
    match = _STATUS_RE.search(text)
    return int(match.group(1)) if match else None
