"""
MCP data source: fetches the Zero Trust topology through Cloudflare's
remote MCP server (https://mcp.cloudflare.com/mcp).

Server transport
================
Cloudflare's API MCP server exposes the whole Cloudflare REST API through
two Code-Mode tools -- ``search`` (introspect the OpenAPI document) and
``execute`` (run JavaScript in an isolated Dynamic Worker sandbox where the
generated code calls ``codemode.request({method, path})``).  The server
proxies those requests to ``api.cloudflare.com`` using the caller's API
token, passed as a Bearer token in the ``Authorization`` header (both user
tokens and account tokens are supported, exactly as for the REST client).

This module implements the client side of that exchange directly with the
``requests`` library -- JSON-RPC 2.0 messages, POSTed to the Streamable HTTP
endpoint, parsing either JSON bodies or ``text/event-stream`` (SSE) frames.
No MCP SDK dependency is required.

Request flow per topology fetch
===============================
    fetch_topology()
      -> initialize handshake            (initialize / initialized)
      -> tools/call {name: "execute",
                     arguments: {code: <generated sandbox JS>}}
           (the JS runs codemode.request() calls inside the sandbox;
              including the pagination loops, and returns only the final
              item list; intermediate pages never cross the wire.
      -> shared.parse_* (same parsers the REST client uses)
      -> CloudflareTopology

Deterministic by design
=======================
The sandboxed JavaScript is generated from fixed templates in this module
(``_JS_LIST``, ``_JS_PAGINATED``, ``_JS_CONFIG``).  No LLM participates in
the fetch path and no dynamic tool selection happens at runtime; the only
configurable items are the module constants documented below.

Customization (module constants)
================================
MCP_URL                  Streamable HTTP endpoint of the MCP server.
                         Overridable via Config.mcp_url / --mcp-url /
                         CLOUDFLARE_MCP_URL.
MCP_PROTOCOL_VERSION     JSON-RPC protocolVersion announced in initialize.
MCP_CLIENT_NAME          clientInfo.name announced in initialize.
MCP_MAX_ATTEMPTS         Retry attempts for transient failures.
MCP_BACKOFF_FACTOR       Base delay (seconds) between retries (factor).
MCP_REQUEST_TIMEOUT      Per-request timeout in seconds.
MCP_EXECUTE_TOOL         Tool name used for the sandboxed request calls.
"""

